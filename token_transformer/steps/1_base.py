import numpy as np

# 1. Задаем случайные входы (3 токена размерности d=4)
X0 = np.random.randn(3, 4)

# --- Стандартный послойный расчет векторов ---
X1_std = X0 + X0 @ X0.T @ X0
X2_std = X1_std + X1_std @ X1_std.T @ X1_std

# --- Альтернативный алгоритм в токенном пространстве через матрицу Грама ---
I = np.eye(3)
D0 = X0 @ X0.T  # Исходная матрица попарных скалярных произведений

# Шаг 1: Эволюция матрицы Грама
D1 = (I + D0) @ D0 @ (I + D0).T

# Шаг 2: Вычисление сквозной матрицы весов токенов W
W = (I + D1) @ (I + D0)

# Шаг 3: Расчет выходов для всех токенов одним умножением
X2_alt = W @ X0

# Проверка: матрицы идентичны
assert np.allclose(X2_std, X2_alt)
print("Тест пройден! Матрицы совпадают.")
