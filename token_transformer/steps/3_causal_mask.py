import numpy as np

# 3 токена, 4 признака
X0 = np.random.randn(3, 4)
I = np.eye(3)

# Причинная маска (запрещаем смотреть в будущее)
M = np.tril(np.ones((3, 3)))

# --- Стандартный послойный расчет векторов с маской ---
# Слой 1
D0_std = X0 @ X0.T
A0_std = D0_std * M  # Обнуляем верхний треугольник
X1_std = X0 + A0_std @ X0

# Слой 2
D1_std = X1_std @ X1_std.T
A1_std = D1_std * M
X2_std = X1_std + A1_std @ X1_std


# --- Расчет через геометрию матриц Грама ---
D0 = X0 @ X0.T

# Слой 1
A0 = D0 * M
D1 = (I + A0) @ D0 @ (I + A0).T

# Слой 2
A1 = D1 * M

# Общая причинная матрица весов W
W = (I + A1) @ (I + A0)

# Финальный расчет
X2_alt = W @ X0

assert np.allclose(X2_std, X2_alt)
print("Тест пройден! Матрицы совпадают.")
